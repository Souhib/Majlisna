"""Woven Sadu bands for the Samar design system.

Ported from the validated sketch's build.py (scratchpad/final/tools/build.py): every band
is a crisp stepped SVG drawn from a pixel grid, so it reads as weaving, not clip-art.

Outputs (both committed, regenerate after editing a grid):
  src/assets/sadu/<name>.svg   one file per band, for <img>, OG cards, design tools
  src/styles/sadu.css          the same bands as data-URI custom properties (--band-*),
                               which is how the app consumes them (CSP img-src allows data:)

Run from front/:  python3 -I scripts/brand/sadu.py
"""
import pathlib
import urllib.parse

FRONT = pathlib.Path(__file__).resolve().parents[2]

WOOL = {
    "K": "#1d1613",  # goat hair, natural black-brown
    "C": "#eadfc8",  # undyed sheep wool
    "R": "#9a3324",  # madder, the ribbon's dark dye bath
    "M": "#d0654f",  # madder, the board's light dye bath (team 1)
    "O": "#c08a3e",  # ochre / camel
    "I": "#243971",  # indigo (team 2)
    "B": "#4a3529",  # natural brown
    "N": "#efe7d8",  # wool cream = the night letters
}


def grid_svg(rows):
    h, w = len(rows), len(rows[0])
    assert all(len(r) == w for r in rows), rows
    rects = []
    for y, row in enumerate(rows):
        x = 0
        while x < w:
            ch, run = row[x], 1
            while x + run < w and row[x + run] == ch:
                run += 1
            rects.append(f'<rect x="{x}" y="{y}" width="{run}" height="1" fill="{WOOL[ch]}"/>')
            x += run
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'shape-rendering="crispEdges" preserveAspectRatio="none">' + "".join(rects) + "</svg>")


def uri(svg):
    return "url(\"data:image/svg+xml," + urllib.parse.quote(svg, safe=" =:/,;'") + "\")"


def madd(selvedge):
    """Al-madd, the kashida band. Selvedge rows in the letters' colour, so the band reads as
    the inside of the stroke, not a gap between two halves of the word."""
    W = 18
    s, k = selvedge, "K" if selvedge != "K" else "C"
    rows = [s * W, "".join(s if i % 2 == 0 else k for i in range(W))]
    field = [["R"] * W for _ in range(7)]
    eye = {0: range(4, 5), 1: range(3, 6), 2: range(2, 7), 3: range(1, 8), 4: range(2, 7), 5: range(3, 6), 6: range(4, 5)}
    for r, cols in eye.items():
        for c in cols:
            field[r][c] = "C"
    field[3][4] = "K"
    for r, cols in {2: [13], 3: [12, 13, 14], 4: [13]}.items():
        for c in cols:
            field[r][c] = "O"
    rows += ["".join(r) for r in field]
    rows += ["".join(k if i % 2 == 0 else s for i in range(W)), s * W]
    return rows


def teeth():
    """Durus, the teeth: team Madder's selvedge."""
    W = 8
    rows = ["K" * W]
    for rng in (range(0, 7), range(1, 6), range(2, 5), range(3, 4)):
        rows.append("".join("K" if i in rng else "M" for i in range(W)))
    for rng in (range(3, 4), range(2, 5), range(1, 6), range(0, 7)):
        sh = {(i + 4) % W for i in rng}
        rows.append("".join("C" if i in sh else "M" for i in range(W)))
    rows.append("K" * W)
    return rows


def ayn():
    """Ayn, the eye: team Indigo's selvedge, undyed eyes on indigo."""
    W = 10
    rows = ["K" * W, "".join("C" if i % 2 == 0 else "K" for i in range(W))]
    field = [["I"] * W for _ in range(5)]
    for r, cols in {0: [4], 1: [3, 5], 2: [2, 4, 6, 9], 3: [3, 5], 4: [4]}.items():
        for c in cols:
            field[r][c] = "C"
    rows += ["".join(r) for r in field]
    rows += ["".join("K" if i % 2 == 0 else "C" for i in range(W)), "K" * W]
    return rows


def goat():
    """The assassin's selvedge: plain goat-hair twill, black on brown."""
    return ["KKBBKKBB", "KBBKKBBK", "BBKKBBKK", "BKKBBKKB"]


def plain():
    """Bystander: plain undyed weave, barely patterned."""
    return ["OOOOOOOO", "CCOCCCOC", "COCCCOCC", "OOOOOOOO"]


def khayt():
    """Khayt, the clock thread: undyed and goat-hair twill, no madder. Reserved for the clock."""
    return ["CCKKCCKK", "CKKCCKKC", "KKCCKKCC", "KCCKKCCK"]


BANDS = {
    "madd-night": madd("N"),
    "madd-day": madd("K"),
    "teeth": teeth(),
    "ayn": ayn(),
    "goat": goat(),
    "plain": plain(),
    "khayt": khayt(),
}


def main():
    css = [
        "/* GENERATED by scripts/brand/sadu.py: do not edit by hand. */",
        "/* The woven Sadu bands as data-URI custom properties. Each tile is a pixel grid; */",
        "/* use them as `background: var(--band-x) left center / auto 100% repeat-x`. */",
        ":root {",
    ]
    for name, rows in BANDS.items():
        svg = grid_svg(rows)
        (FRONT / "src/assets/sadu" / f"{name}.svg").write_text(svg + "\n")
        w, h = len(rows[0]), len(rows)
        css.append(f"  /* {name}: {w}x{h} */")
        css.append(f"  --band-{name}: {uri(svg)};")
        css.append(f"  --band-{name}-ratio: {w / h:.4f};")
    css.append("}")
    (FRONT / "src/styles/sadu.css").write_text("\n".join(css) + "\n")
    print("wrote", len(BANDS), "bands")


if __name__ == "__main__":
    main()
