"""The PostgreSQL schema: Alembic migrations, run by the app at boot (backend/CLAUDE.md, "Migrations").

``migrate_to_head`` is what every uvicorn worker runs in its lifespan on PostgreSQL
(``database.create_schema``), and what ``scripts/generate_fake_data.py`` runs. SQLite (dev,
the default test run) keeps ``create_all`` (``database.create_db_and_tables``): the
migrations are written for PostgreSQL only.

All of it happens in ONE transaction under ``pg_advisory_xact_lock(SCHEMA_DDL_LOCK_KEY)``,
over the connection the caller gives (the direct one, never PgBouncer): the workers take
turns, the first migrates, the next ones find the database at head. The lock is
transaction-scoped, released by the commit or the rollback. A migration that fails rolls
the whole boot's DDL back and the boot fails with it.

A database with no ``alembic_version`` is one of three kinds:

- **empty** (no table at all): it gets every migration, from the baseline up;
- **created before migrations** (production on 2026-11-01, an E2E or dev database built by
  ``create_all``): it is ADOPTED — stamped at the baseline, then upgraded — but only if its
  schema is exactly what the baseline creates. The baseline is built, for the comparison,
  in a schema of its own inside a savepoint that is always rolled back
  (``SCHEMA_ADOPTION_PROBE_SCHEMA``), and both are described from the catalogs
  (``describe_schema``);
- **anything else** (a table missing, a column of another type, an index more or less):
  REFUSED. A version stamp is a promise about the schema that every later migration builds
  on; stamping a database that breaks it would make the next migrations fail, or worse,
  succeed on a schema they were not written for. The boot fails with the differences in
  the log, and nothing is written.
"""

from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from loguru import logger
from sqlalchemy import Connection, Table, UniqueConstraint, text
from sqlalchemy.ext.asyncio import AsyncEngine
from sqlmodel import SQLModel

# Every table on SQLModel.metadata (table.py imports every model): the drop below and
# autogenerate (migrations/env.py) read it.
import majlisna.api.models.table  # noqa: F401
from majlisna.api.constants import (
    ALEMBIC_BASELINE_REVISION,
    ALEMBIC_VERSION_TABLE,
    POSTGRES_ONLY_INDEXES,
    SCHEMA_ADOPTION_PROBE_SCHEMA,
    SCHEMA_DDL_LOCK_KEY,
    SCHEMA_DDL_LOCK_TIMEOUT,
)

BACKEND_DIR = Path(__file__).resolve().parent.parent
ALEMBIC_INI = BACKEND_DIR / "alembic.ini"
# Where migrations/env.py looks for the connection the app hands in.
CONNECTION_ATTRIBUTE = "connection"

# The relations of one schema that are its own: tables (plain and partitioned), minus the
# version table and anything an extension owns (pg_stat_statements' objects, say).
_OWN_TABLES = """
    SELECT c.oid, c.relname
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = :schema AND c.relkind IN ('r', 'p') AND c.relname <> :version_table
      AND NOT EXISTS (
        SELECT 1 FROM pg_depend d
        WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid AND d.deptype = 'e'
      )
"""

# One line per object, rendered by PostgreSQL itself (format_type, pg_get_constraintdef,
# pg_get_indexdef, pg_get_expr) with the described schema alone on the search_path, so
# that no name carries a schema and two schemas compare line for line (pg_get_indexdef
# qualifies its table whatever the search_path: that one prefix is cut). Together: what
# `pg_dump --schema-only` says of tables, columns (in their order), defaults, constraints,
# indexes, enum types (labels in order) and sequences.
_DESCRIBE_QUERIES = (
    f"WITH own AS ({_OWN_TABLES}) SELECT 'table ' || relname FROM own",
    f"""
    WITH own AS ({_OWN_TABLES})
    SELECT format(
        'column %s #%s %s %s%s%s%s',
        own.relname,
        row_number() OVER (PARTITION BY a.attrelid ORDER BY a.attnum),
        a.attname,
        format_type(a.atttypid, a.atttypmod),
        CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
        CASE a.attidentity
            WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
            WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
            ELSE ''
        END,
        coalesce(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), '')
    )
    FROM own
    JOIN pg_attribute a ON a.attrelid = own.oid
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE a.attnum > 0 AND NOT a.attisdropped
    """,
    f"""
    WITH own AS ({_OWN_TABLES})
    SELECT format('constraint %s %s %s', own.relname, con.conname, pg_get_constraintdef(con.oid))
    FROM own JOIN pg_constraint con ON con.conrelid = own.oid
    """,
    f"""
    WITH own AS ({_OWN_TABLES})
    SELECT 'index ' || replace(pg_get_indexdef(i.indexrelid), ' ON ' || quote_ident(:schema) || '.', ' ON ')
    FROM own JOIN pg_index i ON i.indrelid = own.oid
    """,
    """
    SELECT format('enum %s (%s)', t.typname, string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder))
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    JOIN pg_enum e ON e.enumtypid = t.oid
    WHERE n.nspname = :schema
      AND NOT EXISTS (
        SELECT 1 FROM pg_depend d
        WHERE d.classid = 'pg_type'::regclass AND d.objid = t.oid AND d.deptype = 'e'
      )
    GROUP BY t.typname
    """,
    """
    SELECT format(
        'sequence %s %s start %s increment %s min %s max %s cache %s%s owned by %s',
        c.relname,
        format_type(s.seqtypid, NULL),
        s.seqstart,
        s.seqincrement,
        s.seqmin,
        s.seqmax,
        s.seqcache,
        CASE WHEN s.seqcycle THEN ' cycle' ELSE '' END,
        coalesce(owner.relname || '.' || a.attname, 'nothing')
    )
    FROM pg_sequence s
    JOIN pg_class c ON c.oid = s.seqrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_depend d
        ON d.classid = 'pg_class'::regclass AND d.objid = c.oid
        AND d.refclassid = 'pg_class'::regclass AND d.deptype IN ('a', 'i')
    LEFT JOIN pg_class owner ON owner.oid = d.refobjid
    LEFT JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
    WHERE n.nspname = :schema
      AND NOT EXISTS (
        SELECT 1 FROM pg_depend e
        WHERE e.classid = 'pg_class'::regclass AND e.objid = c.oid AND e.deptype = 'e'
      )
    """,
)


class SchemaAdoptionRefusedError(RuntimeError):
    """A database without alembic_version whose schema is not exactly the baseline's."""

    def __init__(self, missing: list[str], unexpected: list[str]):
        self.missing = missing
        self.unexpected = unexpected
        lines = [f"  - missing:    {line}" for line in missing] + [f"  - unexpected: {line}" for line in unexpected]
        super().__init__(
            "Schema: refusing to adopt this database. It has tables but no alembic_version, and its "
            f"schema is not the one the baseline revision ({ALEMBIC_BASELINE_REVISION}) creates, so "
            "stamping it would be a lie every later migration builds on. Nothing was written. "
            "Differences:\n" + "\n".join(lines) + "\n"
            "A dev or E2E database: drop it and let the boot build it (--delete then --create-db, or "
            "`docker compose -f e2e/docker-compose.e2e.yml down -v`). A server: make its schema "
            "the baseline's by hand (after a pg_dump), or stamp it by hand if the difference is "
            "known and wanted (`alembic stamp " + ALEMBIC_BASELINE_REVISION + "`), then boot again."
        )


def alembic_config(connection: Connection | None = None) -> Config:
    """The project's Alembic configuration, running on ``connection`` when one is given."""
    config = Config(str(ALEMBIC_INI))
    if connection is not None:
        config.attributes[CONNECTION_ATTRIBUTE] = connection
    return config


def include_object(
    object_: object,
    name: str | None,
    type_: str,
    reflected: bool,
    compare_to: object | None,
) -> bool:
    """What autogenerate compares: everything but two things PostgreSQL has no row for.

    - The PostgreSQL-only indexes (``POSTGRES_ONLY_INDEXES``): created by the migrations,
      declared by no model, so every autogenerate would offer to drop them.
    - A model's UNIQUE that repeats its primary key (``unique=True`` on most ``id``
      fields): PostgreSQL drops such a constraint inside its CREATE TABLE, so no database
      has it, production included, and every autogenerate would offer to add it.
    """
    if type_ == "index" and reflected and compare_to is None:
        return name not in POSTGRES_ONLY_INDEXES
    if type_ == "unique_constraint" and not reflected and isinstance(object_, UniqueConstraint):
        return not _repeats_primary_key(object_)
    return True


def _repeats_primary_key(constraint: UniqueConstraint) -> bool:
    table = constraint.table
    if not isinstance(table, Table):
        return False
    return {column.name for column in constraint.columns} == {column.name for column in table.primary_key.columns}


def lock_schema(connection: Connection) -> None:
    """Take the schema lock for the transaction, then bound every other lock wait.

    Blocking and unbounded first: a worker that waits here then sees, through fresh READ
    COMMITTED snapshots, everything the one before it committed. ``lock_timeout`` comes
    after, transaction-local, for the DDL itself. Taking it twice in one transaction (the
    app, then migrations/env.py) is harmless: advisory locks stack.
    """
    connection.execute(text("SELECT pg_advisory_xact_lock(:key)"), {"key": SCHEMA_DDL_LOCK_KEY})
    connection.execute(text("SELECT set_config('lock_timeout', :timeout, true)"), {"timeout": SCHEMA_DDL_LOCK_TIMEOUT})


def describe_schema(connection: Connection, schema: str | None = None) -> list[str]:
    """The sorted catalog description of ``schema`` (default: the current one), version table aside."""
    search_path = connection.execute(text("SELECT current_setting('search_path')")).scalar_one()
    target = schema or connection.execute(text("SELECT current_schema()")).scalar_one()
    _set_search_path(connection, target)
    try:
        params = {"schema": target, "version_table": ALEMBIC_VERSION_TABLE}
        lines = [line for query in _DESCRIBE_QUERIES for line in connection.execute(text(query), params).scalars()]
    finally:
        connection.execute(text("SELECT set_config('search_path', :path, true)"), {"path": search_path})
    return sorted(lines)


async def migrate_to_head(engine: AsyncEngine, *, drop_first: bool = False) -> None:
    """Bring the PostgreSQL database behind ``engine`` to the head revision, in one locked transaction.

    ``drop_first`` drops every table first (and the version table): only for
    ``scripts/generate_fake_data.py --delete``, which refuses production.
    """
    async with engine.begin() as conn:
        await conn.run_sync(_migrate_to_head, drop_first)


def _migrate_to_head(connection: Connection, drop_first: bool) -> None:
    lock_schema(connection)
    if drop_first:
        SQLModel.metadata.drop_all(connection)
        connection.execute(text(f'DROP TABLE IF EXISTS "{ALEMBIC_VERSION_TABLE}"'))
    config = alembic_config(connection)
    if not _has_version_table(connection) and _has_tables(connection):
        _adopt(connection, config)
    before = _current_revision(connection)
    command.upgrade(config, "head")
    after = _current_revision(connection)
    if after != before:
        logger.info("Schema: migrated from {} to {}", before or "an empty database", after)


def _adopt(connection: Connection, config: Config) -> None:
    """Stamp a database created before migrations at the baseline, if its schema is the baseline's."""
    expected = set(_baseline_description(connection))
    actual = set(describe_schema(connection))
    missing, unexpected = sorted(expected - actual), sorted(actual - expected)
    if missing or unexpected:
        error = SchemaAdoptionRefusedError(missing, unexpected)
        logger.error(str(error))
        raise error
    command.stamp(config, ALEMBIC_BASELINE_REVISION)
    logger.warning(
        "Schema: adopted a database created before migrations: its schema is the baseline's, stamped at {}",
        ALEMBIC_BASELINE_REVISION,
    )


def _baseline_description(connection: Connection) -> list[str]:
    """What the baseline revision creates, built in a probe schema that is always rolled back."""
    search_path = connection.execute(text("SELECT current_setting('search_path')")).scalar_one()
    savepoint = connection.begin_nested()
    try:
        connection.execute(text(f'CREATE SCHEMA "{SCHEMA_ADOPTION_PROBE_SCHEMA}"'))
        _set_search_path(connection, SCHEMA_ADOPTION_PROBE_SCHEMA)
        command.upgrade(alembic_config(connection), ALEMBIC_BASELINE_REVISION)
        return describe_schema(connection, SCHEMA_ADOPTION_PROBE_SCHEMA)
    finally:
        savepoint.rollback()
        connection.execute(text("SELECT set_config('search_path', :path, true)"), {"path": search_path})


def _set_search_path(connection: Connection, schema: str) -> None:
    connection.execute(text("SELECT set_config('search_path', quote_ident(:schema), true)"), {"schema": schema})


def _has_version_table(connection: Connection) -> bool:
    return connection.execute(
        text("SELECT to_regclass(:name) IS NOT NULL"), {"name": ALEMBIC_VERSION_TABLE}
    ).scalar_one()


def _has_tables(connection: Connection) -> bool:
    """Whether the current schema holds any table of its own (an extension's do not count)."""
    query = f"SELECT EXISTS ({_OWN_TABLES})"
    schema = connection.execute(text("SELECT current_schema()")).scalar_one()
    return connection.execute(text(query), {"schema": schema, "version_table": ALEMBIC_VERSION_TABLE}).scalar_one()


def _current_revision(connection: Connection) -> str | None:
    return MigrationContext.configure(connection).get_current_revision()
